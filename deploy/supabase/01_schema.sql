-- ============================================================================
--  exmsys · 心理咨询师考试背题系统
--  云端 PostgreSQL 建库脚本（Supabase / Neon / Aiven 通用）
--                                          文件：01_schema.sql
-- ----------------------------------------------------------------------------
--  来源   ：本地 SQLite 库 data/exmsys.db 的结构快照（2026-10-08 导出）
--  执行   ：云端控制台的 SQL Editor -> 【整段一次性】粘贴 -> Run（三家都一样）
--           ⚠️ Neon / Aiven 请用【直连】端点执行，不要用连接池端点（-pooler / 非 5432 端口）：
--              连接池是 PgBouncer transaction 模式，不支持会话级语义，DDL 可能中途失败。
--  目标库 ：独立 schema `psych_exm`（不是 public）—— 见下面第 0 节
--  幂等性 ：全部使用 create table if not exists / 可重复执行，重跑不报错
--  平台差异：仅第 6 节的 anon / authenticated 授权回收是 Supabase 专属，
--           脚本内已做角色存在性判断，其他平台自动跳过。
-- ----------------------------------------------------------------------------
--  设计原则（重要，别改）
--  1) 表名 / 列名 / 列语义与 SQLite 版【逐字一致】，不做任何重命名，
--     这样数据访问层（utils/data_access.py）只需换连接与方言，页面层零改动。
--  2) 类型映射约定：
--       TEXT                              -> text
--       INTEGER                           -> integer
--       INTEGER PRIMARY KEY AUTOINCREMENT -> bigint generated by default as identity
--       REAL                              -> double precision
--  3) 所有日期时间字段【保持 text】。库里存的是 Python 侧生成的 ISO 字符串，
--     换成 timestamptz 会引入时区与格式转换，反而破坏与现有代码的兼容。
--  4) is_correct / last_correct / unstable / is_case_background 等【保持 integer】
--     而不是 boolean：现有代码读写的是 0/1，换 boolean 必须改 SQL，得不偿失。
--  5) 公共题库 owner 仍用哨兵值 '__public__' 而不是 NULL ——
--     PostgreSQL 与 SQLite 一样「NULL 互不相等」，若用 NULL，
--     UNIQUE(owner_id, md5) 会直接失效（公共题库去重坏掉）。
-- ============================================================================


-- ============================================================================
--  0. 目标 schema —— 要改就只改这一节（共 3 处字面量）
-- ----------------------------------------------------------------------------
--  为什么用独立 schema：一个 Supabase 项目 = 一个 PostgreSQL 实例，实例里可以建
--  任意多个 schema。本实例的 public 已被【另一个应用】占用，所以本项目放到
--  独立的 psych_exm 里：两边表名互不干扰（users / drafts 这类名字两边都可能存在）、
--  权限各自独立、备份恢复时也不会互相覆盖。
--
--  额外好处（Supabase 官方文档已确认）：自建的 schema 默认**不在
--  API Settings -> Exposed schemas 列表里**（默认只有 public / graphql_public），
--  因此它根本不会出现在 Data API 上 —— 别人拿着本项目的 anon key 也触不到这些表。
--  ⚠️ 所以：**不要**把 psych_exm 加进 Exposed schemas。
--  注意区分：表里的 owner_id = '__public__' 是【数据层的哨兵值】，与本节的
--  数据库 schema（命名空间）是两回事，别混淆。
--
--  ⚠️⚠️ 本脚本依赖下面的 `set search_path`：第 1~7 节所有表名都是**不带前缀的裸名**。
--      因此必须【整段一次性执行】：
--        · 控制台 SQL Editor 全文粘贴 → Run                              ✔ 正确
--        · 逐条选中执行                                                    ✘ 错误
--      因为逐条执行时每条语句是独立会话，set search_path 会丢失，
--      紧接着的断言块会**立刻报错中止** —— 宁可报错，也绝不把表静默建到 public 里
--      去污染另一个应用（那是这个设计里最致命的失败模式）。
--
--  要换 schema 名：改下面这 3 处（create / set / 断言里的字符串）即可，
--  第 1~8 节全部用 current_schema() 或裸名，不需要再改。
-- ============================================================================

create schema if not exists psych_exm;

set search_path to psych_exm;

do $$
begin
    if current_schema() <> 'psych_exm' then
        raise exception
            'search_path 未生效：当前解析到 schema = %。本脚本必须【整段一次性执行】，'
            '逐条执行会丢失 set search_path，导致表被建到错误的 schema 里。',
            current_schema();
    end if;
end $$;


