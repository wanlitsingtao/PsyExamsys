-- ============================================================================
--  6. 关闭 Data API 暴露（安全）
-- ----------------------------------------------------------------------------
--  背景：Supabase 会把 public 架构通过 PostgREST 以 anon / authenticated
--  密钥公开出去。本应用走的是【直连 Postgres】（psycopg2），自己用 user_id/owner_id
--  做隔离，根本不需要 PostgREST；若不加限制，任何人拿到项目里的 anon key
--  就能读写全部题库与用户数据。
--
--  注意：本项目用的是独立 schema（psych_exm），而 Supabase 的 PostgREST 默认
--  **只暴露 public / graphql_public** —— 也就是说 psych_exm 本来就不在
--  Data API 的可见范围里（前提：不要把它加进 Exposed schemas）。
--  本节属于【纵深防御】：万一以后有人误把 psych_exm 加进 Exposed schemas，
--  这里的 RLS + REVOKE 仍然挡得住。
--
--  做法：给目标 schema 下所有表开启 RLS 且【一条策略都不建】= 拒绝
--        anon/authenticated 的一切访问；同时收回表级 / 序列级 / schema 级权限。
--        应用连接用的角色是表 Owner，默认绕过 RLS，读写不受影响。
--
--  为什么全部用 current_schema() 拼 SQL 而不是写死 schema 名：
--    本文件第 0 节的 set search_path 已经把 current_schema() 锚定到 psych_exm，
--    这样换 schema 名时不必再回来改这一节。
--
--  ⚠️ 跨平台注意（Neon / Aiven / 自建 PostgreSQL）：
--     anon 与 authenticated 是【Supabase 内置角色】。其他平台没有这两个角色，
--     无条件 REVOKE 会抛 "role \"anon\" does not exist" 并中断整个脚本
--     （SQL Editor / psql 默认在错误处停止，后面的序列对齐和第 7 节就跑不到了）。
--     所以这里先查 pg_roles 判断角色存在才执行。
--     RLS 本身是原生 PostgreSQL 特性，各平台都能开；对没有 PostgREST 的平台
--     属于无害的额外加固（Owner 绕过，应用读写不受影响）。
-- ============================================================================

do $$
declare
    t            text;
    sch          text := current_schema();
    needs_revoke boolean;
    tbls text[] := array[
        'users', 'user_devices', 'app_config', 'user_config',
        'questions', 'case_studies', 'question_stats', 'wrong_questions',
        'answer_records', 'exam_records', 'mock_exam_records',
        'study_records', 'drafts'
    ];
begin
    -- 只有 Supabase 才有 anon / authenticated（PostgREST 的两个匿名角色）
    select exists (select 1 from pg_roles where rolname = 'anon')
       and exists (select 1 from pg_roles where rolname = 'authenticated')
      into needs_revoke;

    foreach t in array tbls loop
        execute format('alter table %I.%I enable row level security;', sch, t);
        if needs_revoke then
            execute format('revoke all on table %I.%I from anon, authenticated;', sch, t);
        end if;
    end loop;

    -- 序列权限一并收回（同样只在角色存在时执行）
    if needs_revoke then
        execute format(
            'revoke all on all sequences in schema %I from anon, authenticated', sch);
        -- schema 级 USAGE / CREATE 也收回：挡住"能进命名空间"这条路
        -- （表级 REVOKE 已经挡了数据访问，这里是第二道闸）
        execute format(
            'revoke all on schema %I from anon, authenticated', sch);
    end if;
end $$;


-- ============================================================================
--  7. 自增序列对齐（导入数据【之后】再执行，或直接跑 02_import 脚本自动完成）
-- ----------------------------------------------------------------------------
--  导入时是显式指定 id 灌入的，序列不会自动前进；不 setval 的话，
--  应用下一条 INSERT 会从 1 开始，直接主键冲突。
--
--  下面的表名是裸名，靠第 0 节的 set search_path 解析到 psych_exm。
--  若单独拷贝到新会话执行，会报 "relation does not exist" —— 这是刻意的：
--  报错比静默对齐到别的 schema 里的同名表安全得多。
-- ============================================================================

select setval(pg_get_serial_sequence('answer_records', 'id'),
              coalesce((select max(id) from answer_records), 1),
              (select max(id) from answer_records) is not null);
select setval(pg_get_serial_sequence('exam_records', 'id'),
              coalesce((select max(id) from exam_records), 1),
              (select max(id) from exam_records) is not null);
select setval(pg_get_serial_sequence('mock_exam_records', 'id'),
              coalesce((select max(id) from mock_exam_records), 1),
              (select max(id) from mock_exam_records) is not null);


-- ============================================================================
--  建库完成自检：应返回 13 行，每行 has_rls = t
--  schema_name 列应等于第 0 节设置的目标 schema（psych_exm）——
--  如果它显示 public，说明本脚本被逐条执行了，请重新整段执行。
-- ============================================================================

select current_schema()                                       as schema_name,
       c.relname                                              as table_name,
       c.relrowsecurity                                       as has_rls,
       (select count(*) from pg_index i
         where i.indrelid = c.oid and i.indisprimary)          as pk_count
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
 where n.nspname = current_schema()
   and c.relkind = 'r'
   and c.relname in ('users','user_devices','app_config','user_config',
                     'questions','case_studies','question_stats','wrong_questions',
                     'answer_records','exam_records','mock_exam_records',
                     'study_records','drafts')
 order by c.relname;


-- ============================================================================
--  类型约定守卫：本 schema 里不得存在 boolean 列
--
--  SQLite 用 INTEGER 存布尔（True / False 落库就是 1 / 0），PG 侧的表结构
--  逐字照搬 SQLite，所以整库靠 integer 模拟布尔、一个 boolean 列都没有。
--  方言层 utils/data_access_pg.py 的 _normalize_params() 会把 Python bool
--  统一归一成 0/1 再交给驱动 —— 依据正是「这一侧没有 boolean 列」。
--  一旦这里混进 boolean 列，归一化反而会让它写不进去（0/1 不是 boolean）。
--
--  背景（2026-10-09 真实事故）：question_stats.unstable / last_correct 收到
--  Python bool 时报 DatatypeMismatch: column "unstable" is of type integer
--  but expression is of type boolean —— PG 不做 boolean → integer 隐式转换。
--
--  注：DO 块里的 plpgsql 局部变量（如第 6 节的 needs_revoke boolean）
--      是过程变量、不属于任何表，不会出现在 information_schema.columns 里。
-- ============================================================================

do $$
declare
    bad text;
begin
    select string_agg(table_name || '.' || column_name, ', ')
      into bad
      from information_schema.columns
     where table_schema = current_schema()
       and data_type = 'boolean';

    if bad is not null then
        raise exception
            '目标 schema 里出现了 boolean 列：%。SQLite 用 INTEGER 存布尔，'
            'PG 侧必须逐字一致，否则方言层的 bool 归一化会失效。', bad;
    end if;
end $$;
